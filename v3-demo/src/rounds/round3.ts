// @cealis/v3-demo/rounds/round3.ts — M8 Round 3: SD On (Parallel Pipelines).
//
// MISSION (internal build brief):
//   Demonstrate parallel-pipeline asymmetric isolation of escrow vs SD.
//   At onboarding (T=0): M6 SD pipeline produces per-field Poseidon
//   commitments + PLONK proof (`range`/age_over_18) + cleartext
//   (cleartext_zk_opened mode per S2-7 §4.4 default). Bundle delivered
//   DAY-ONE to recipient — NOT at TimeLock fire. Escrow pipeline anchors
//   h_commit and waits for TimeLock fire at T+24h (CI sim / 300s live).
//   At TimeLock fire: escrow reveal proceeds; recipient receives ESCROW
//   bundle. Recipient ends up with BOTH bundles, verifiable independently.
//
// ONE-WAY EDGE (S2-7 §15 + memory project_phase_d_closed_2026_05_06):
//   DEK → HKDF → sd_master_salt is the only directional path. NOTHING
//   flows back from SD into escrow. The architectural smoke test asserts
//   this by re-running the boundary's executeIfEscrowOk over a synthetic
//   SD failure and verifying the escrow result is preserved verbatim.
//
// DOCTRINE (PHASE-PLAN §0 drift #3):
//   σ-as-AUTHORIZATION — combiner via @cealis/v3-custody `combineAndDecrypt`
//   over per-stanza wrapped shares; NO HKDF over σ values.
//
// ACCESS STRUCTURE (PHASE-PLAN §0 drift #4):
//   FIXED_ONLY = 3-of-3 Shamir over {Lit, G3=drand, G4=Phase 1}. σ_subject
//   is commit-time consent bound into commit_AAD per S2-1 §5.2; NOT a share.
//
// MODE B GUARD (S2-7 §14):
//   Mode B + SD = forbidden. Round 3 happy path uses Mode A. Phase E tests
//   the rejection path; we surface a structural check only here.
//
// EXECUTION MODES:
//   - "structural" (default for vitest): Composes the round logic against
//     synthetic fixtures + stub adapters. No infra required. Asserts
//     correctness of composition, bundle shape, day-one timing, asymmetric
