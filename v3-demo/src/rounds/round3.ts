/**
 * Verifier registry — by default returns a stub verifier whose `verifyProof`
 * always returns true (asserts SDK call SHAPE, not crypto content; keeps
 * vitest CI ~2s). Under `VITEST_PLONK_REAL=1` the verifier callback decodes
 * the claim's hex-encoded proof JSON and runs a real `snarkjs plonk verify`
 * against the v3-sd `range` vkey (~5-10s/verify). The cleartext-opening
 * verifier_ref still resolves to the always-true stub (the opening proof
 * is synthetic in both modes; only the claim's range proof can be made
 * real because we have the matching circuit + setup). See the internal
 * integration-gap log.
 *
 * Returns a registered verifier for ANY well-formed non-zero verifier_ref.
 * The round structurally generates two verifier_refs (claim + cleartext-
 * opening), both of which must resolve to a verifier in the registry.
 */
function stubVerifierRegistry(claimVerifierRef: `0x${string}`): VerifierRegistryClient {
  const useRealPlonk = process.env.VITEST_PLONK_REAL === "1";
  const claimRefLower = claimVerifierRef.toLowerCase();

  const alwaysTrueVerifier: Verifier = {
    publicInputSchemaDigest: undefined,
    verifyProof: () => true,
  };

  const realRangeVerifier: Verifier = {
    publicInputSchemaDigest: undefined,
    verifyProof: (proof, publicInputs) => {
      // Decode the hex-encoded JSON proof produced by sdEmit() above.
      const proofHex = typeof proof === "string" ? proof : "";
      if (!proofHex.startsWith("0x")) return false;
      try {
        const proofJson = Buffer.from(proofHex.slice(2), "hex").toString("utf-8");
        const proofObj: unknown = JSON.parse(proofJson);
        return verifyPlonkProof("range", proofObj, publicInputs);
      } catch {
        return false;
      }
    },
  };

  return {
    getVerifierAt: (ref) => {
      // Accept any well-formed non-zero verifier_ref. The structural test
      // surface needs the SDK to drive the full verify flow; rejecting at
      // registry-lookup time would short-circuit the test.
      if (typeof ref !== "string" || !/^0x[0-9a-f]{64}$/i.test(ref)) return null;
      if (/^0x0+$/i.test(ref)) return null;
      // Real-mode: route only the CLAIM verifier_ref to the real verifier.
      // The cleartext-opening verifier_ref keeps the always-true stub —
      // we don't ship a circuit for that opening proof, only the SDK
      // call-shape contract (the synthetic 192-byte cd-proof satisfies it).
      if (useRealPlonk && ref.toLowerCase() === claimRefLower) {
        return realRangeVerifier;
      }
      return alwaysTrueVerifier;
    },
  };
}

