function randomHex32(seed: string): `0x${string}` {
  const bytes = keccak_256(new TextEncoder().encode(seed));
  let hex = "0x";
  for (const b of bytes) hex += b.toString(16).padStart(2, "0");
  return hex as `0x${string}`;
}

